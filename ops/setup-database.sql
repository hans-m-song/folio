\set ON_ERROR_STOP on
\set ECHO none
\set VERBOSITY terse
\set SHOW_CONTEXT never
\getenv folio_app_password FOLIO_DATABASE_APP_PASSWORD
\getenv folio_admin_password FOLIO_DATABASE_ADMIN_PASSWORD

BEGIN;

SELECT pg_catalog.pg_advisory_xact_lock(
  pg_catalog.hashtext('folio-migrations:folio')
);

CREATE ROLE folio_app
  LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
  NOREPLICATION NOBYPASSRLS NOINHERIT
  PASSWORD :'folio_app_password';

CREATE ROLE folio_admin
  LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
  NOREPLICATION NOBYPASSRLS NOINHERIT
  PASSWORD :'folio_admin_password';

CREATE SCHEMA folio;

SELECT pg_catalog.format(
  'REVOKE CREATE ON DATABASE %I FROM folio_app',
  pg_catalog.current_database()
) \gexec

REVOKE CREATE ON SCHEMA folio FROM PUBLIC;
REVOKE CREATE ON SCHEMA folio FROM folio_app;
GRANT USAGE ON SCHEMA folio TO folio_app;
GRANT USAGE, CREATE ON SCHEMA folio TO folio_admin;

GRANT folio_admin TO SESSION_USER WITH SET TRUE;
SET LOCAL ROLE folio_admin;

ALTER DEFAULT PRIVILEGES
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA folio
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA folio
  GRANT SELECT ON TABLES TO folio_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA folio
  GRANT USAGE, SELECT ON SEQUENCES TO folio_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA folio
  GRANT EXECUTE ON FUNCTIONS TO folio_app;

RESET ROLE;
REVOKE folio_admin FROM SESSION_USER;

COMMIT;
